/* ========================================================
 * TEST 11: Todos los tipos de constantes numéricas
 * Objetivo: Verificar decimales, octales, hexadecimales,
 *           flotantes, y constantes con sufijos.
 * ======================================================== */

int main() {
    /* Decimales */
    int a = 0;
    int b = 1;
    int c = 42;
    int d = 123456789;

    /* Octales */
    int e = 077;
    int f = 0123;
    int g = 07;

    /* Hexadecimales */
    int h = 0x0;
    int i = 0xFF;
    int j = 0XABCDef;
    int k = 0x1A2B;

    /* Flotantes */
    double l = 3.14;
    double m = .5;
    double n = 10.;
    double o = 1.0e10;
    double p = 2.5E-3;
    double q = .5e+2;
    float r = 3.14f;
    float s = 1.0F;
    long double t = 2.718L;

    /* Constante de caracter */
    char u = 'a';
    char v = '\n';
    char w = '\\';
    char x = '\'';
    char y = '\0';
    char z = '\t';

    return 0;
}
