/*
 * Statistics used by the presentation.
 *
 * These values are calculated directly from the token array
 * produced by the scanner.
 */
typedef struct {
    size_t keyword_count;
    size_t identifier_count;
    size_t constant_count;
    size_t string_literal_count;
    size_t operator_count;
    size_t punctuator_count;
    size_t error_count;
    size_t total_tokens;
} BeamerStats;

static void write_code_legend(
    FILE *file
);

static int write_source_slides(
    FILE *file,
    const char *preprocessed_filename,
    const Token *tokens,
    size_t token_count
);

/*
 * Calculates lexical-category statistics from the tokens
 * generated by the scanner.
 */
static void calculate_stats(
    const Token *tokens,
    size_t token_count,
    BeamerStats *stats
) {
    memset(stats, 0, sizeof(BeamerStats));

    for (size_t i = 0; i < token_count; i++) {

        switch (tokens[i].category) {

            case CAT_KEYWORD:
                stats->keyword_count++;
                break;

            case CAT_IDENTIFIER:
                stats->identifier_count++;
                break;

            case CAT_CONSTANT:
                stats->constant_count++;
                break;

            case CAT_STRING_LITERAL:
                stats->string_literal_count++;
                break;

            case CAT_OPERATOR:
                stats->operator_count++;
                break;

            case CAT_PUNCTUATOR:
                stats->punctuator_count++;
                break;

            case CAT_ERROR:
                stats->error_count++;
                break;

            case CAT_EOF:
                continue;
        }

        stats->total_tokens++;
    }
}


/*
 * Prints text safely inside LaTeX.
 *
 * Some characters have a special meaning in LaTeX and must
 * therefore be escaped before being written to the .tex file.
 */
static void write_latex_escaped(
    FILE *file,
    const char *text
) {
    if (text == NULL) {
        return;
    }

    while (*text != '\0') {

        switch (*text) {

            case '\\':
                fprintf(file, "\\textbackslash{}");
                break;

            case '{':
                fprintf(file, "\\{");
                break;

            case '}':
                fprintf(file, "\\}");
                break;

            case '$':
                fprintf(file, "\\$");
                break;

            case '&':
                fprintf(file, "\\&");
                break;

            case '#':
                fprintf(file, "\\#");
                break;

            case '_':
                fprintf(file, "\\_");
                break;

            case '%':
                fprintf(file, "\\%%");
                break;

            case '^':
                fprintf(file, "\\textasciicircum{}");
                break;

            case '~':
                fprintf(file, "\\textasciitilde{}");
                break;

            default:
                fputc(*text, file);
                break;
        }

        text++;
    }
}

static void write_code_escaped(
    FILE *file,
    const char *text
) {
    if (file == NULL || text == NULL) {
        return;
    }

    for (const char *p = text; *p != '\0'; p++) {

        switch (*p) {

            case '\\':
                fprintf(file, "\\textbackslash{}");
                break;

            case '{':
                fprintf(file, "\\{");
                break;

            case '}':
                fprintf(file, "\\}");
                break;

            case '$':
                fprintf(file, "\\$");
                break;

            case '&':
                fprintf(file, "\\&");
                break;

            case '#':
                fprintf(file, "\\#");
                break;

            case '_':
                fprintf(file, "\\_");
                break;

            case '%':
                fprintf(file, "\\%%");
                break;

            case '^':
                fprintf(file, "\\textasciicircum{}");
                break;

            case '~':
                fprintf(file, "\\textasciitilde{}");
                break;

            /*
             * Avoid LaTeX converting -- into
             * a typographical dash.
             */
            case '-':
                fprintf(file, "\\char45{}");
                break;

            default:
                fputc(*p, file);
                break;
        }
    }
}

static const char *category_color(
    TokenCategory category
) {
    switch (category) {

        case CAT_KEYWORD:
            return "keywordcolor";

        case CAT_IDENTIFIER:
            return "identifiercolor";

        case CAT_CONSTANT:
            return "constantcolor";

        case CAT_STRING_LITERAL:
            return "stringcolor";

        case CAT_OPERATOR:
            return "operatorcolor";

        case CAT_PUNCTUATOR:
            return "punctuatorcolor";

        case CAT_ERROR:
            return "errorcolor";

        case CAT_EOF:
            return "black";
    }

    return "black";
}

static void write_styled_token(
    FILE *file,
    const Token *token
) {
    if (file == NULL ||
        token == NULL ||
        token->lexeme == NULL) {

        return;
    }

    const char *command = NULL;

    switch (token->category) {

        case CAT_KEYWORD:
            command = "tokkeyword";
            break;

        case CAT_IDENTIFIER:
            command = "tokidentifier";
            break;

        case CAT_CONSTANT:
            command = "tokconstant";
            break;

        case CAT_STRING_LITERAL:
            command = "tokstring";
            break;

        case CAT_OPERATOR:
            command = "tokoperator";
            break;

        case CAT_PUNCTUATOR:
            command = "tokpunctuator";
            break;

        case CAT_ERROR:
            command = "tokerror";
            break;

        case CAT_EOF:
            return;
    }

    fprintf(
        file,
        "(*@\\%s{",
        command
    );

    write_code_escaped(
        file,
        token->lexeme
    );

    fprintf(
        file,
        "}@*)"
    );
}

static size_t count_source_lines(
    FILE *input
) {
    if (input == NULL) {
        return 0;
    }

    size_t lines = 0;

    int character;
    int last_character = '\n';
    int has_content = 0;

    rewind(input);

    while ((character = fgetc(input)) != EOF) {

        has_content = 1;

        if (character == '\n') {
            lines++;
        }

        last_character = character;
    }

    /*
     * Count the last line if the file does not end
     * with a newline.
     */
    if (has_content &&
        last_character != '\n') {

        lines++;
    }

    rewind(input);

    return lines;
}

static void write_source_line(
    FILE *file,
    const char *line,
    size_t line_number,
    const Token *tokens,
    size_t token_count,
    size_t *token_index
) {
    if (file == NULL ||
        line == NULL ||
        tokens == NULL ||
        token_index == NULL) {

        return;
    }

    size_t line_length = strlen(line);

    /*
     * getline() includes the newline character.
     * listings will receive the newline separately.
     */
    while (line_length > 0 &&
           (line[line_length - 1] == '\n' ||
            line[line_length - 1] == '\r')) {

        line_length--;
    }

    size_t cursor = 0;

    /*
     * Normally this should not be necessary because
     * tokens are ordered, but it keeps the function
     * defensive.
     */
    while (*token_index < token_count &&
           tokens[*token_index].line <
               (int) line_number) {

        (*token_index)++;
    }

    while (*token_index < token_count &&
           tokens[*token_index].line ==
               (int) line_number) {

        const Token *token =
            &tokens[*token_index];

        if (token->lexeme == NULL) {

            (*token_index)++;
            continue;
        }

        /*
         * Scanner columns are assumed to start at 1.
         */
        size_t token_start = 0;

        if (token->column > 0) {
            token_start =
                (size_t) token->column - 1;
        }

        /*
         * Prevent invalid positions from reading beyond
         * the current source line.
         */
        if (token_start > line_length) {
            token_start = line_length;
        }

        /*
         * Write all untouched characters before the token.
         * These are normally spaces or tabs.
         */
        if (token_start > cursor) {

            fwrite(
                line + cursor,
                sizeof(char),
                token_start - cursor,
                file
            );
        }

        /*
         * Replace the original lexeme with the styled
         * representation of the token.
         */
        write_styled_token(
            file,
            token
        );

        size_t token_length =
            strlen(token->lexeme);

        size_t token_end =
            token_start + token_length;

        if (token_end > line_length) {
            token_end = line_length;
        }

        cursor = token_end;

        (*token_index)++;
    }

    /*
     * Write any remaining text after the last token.
     */
    if (cursor < line_length) {

        fwrite(
            line + cursor,
            sizeof(char),
            line_length - cursor,
            file
        );
    }

    fputc('\n', file);
}

static int write_source_slides(
    FILE *file,
    const char *preprocessed_filename,
    const Token *tokens,
    size_t token_count
) {
    if (file == NULL ||
        preprocessed_filename == NULL ||
        tokens == NULL) {

        return 0;
    }

    FILE *input =
        fopen(
            preprocessed_filename,
            "r"
        );

    if (input == NULL) {

        fprintf(
            stderr,
            "Error: could not open "
            "preprocessed source file: %s\n",
            preprocessed_filename
        );

        return 0;
    }

    size_t total_lines =
        count_source_lines(input);

    /*
     * Empty source file.
     */
    if (total_lines == 0) {

        fprintf(
            file,
            "\\begin{frame}"
            "{Preprocessed Source Code}\n"
            "\\centering\n"
            "\\vfill\n"
            "The preprocessed source file is empty.\n"
            "\\vfill\n"
            "\\end{frame}\n\n"
        );

        fclose(input);

        return 1;
    }

    char *line = NULL;
    size_t line_capacity = 0;

    size_t current_line = 1;
    size_t token_index = 0;

    while (current_line <= total_lines) {

        size_t first_line =
            current_line;

        size_t last_line =
            first_line +
            SOURCE_LINES_PER_SLIDE - 1;

        if (last_line > total_lines) {
            last_line = total_lines;
        }

        /*
         * lstlisting requires a fragile Beamer frame.
         */
        fprintf(
            file,
            "\\begin{frame}[fragile]"
            "{Preprocessed Source Code -- "
            "Lines %zu--%zu}\n"
            "\\vspace{-0.15cm}\n"
            "\n",
            first_line,
            last_line
        );

        fprintf(
            file,
            "\\begin{lstlisting}["
            "style=sourcecode,"
            "firstnumber=%zu]\n",
            first_line
        );

        while (current_line <= last_line) {

            ssize_t read =
                getline(
                    &line,
                    &line_capacity,
                    input
                );

            if (read == -1) {
                break;
            }

            write_source_line(
                file,
                line,
                current_line,
                tokens,
                token_count,
                &token_index
            );

            current_line++;
        }

        fprintf(
            file,
            "\\end{lstlisting}\n"
        );

        /*
         * Keep the legend visible on every code slide.
         */
        write_code_legend(file);

        fprintf(
            file,
            "\\end{frame}\n"
            "\n"
        );
    }

    free(line);

    fclose(input);

    return 1;
}

