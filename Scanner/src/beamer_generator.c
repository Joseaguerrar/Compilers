/*
 * Generates the complete Beamer .tex file.
 */
int beamer_generate(
    const char *output_filename,
    const char *source_filename,
    const char *preprocessed_filename,
    const Token *tokens,
    size_t token_count
) {

    if (output_filename == NULL ||
        source_filename == NULL ||
        preprocessed_filename == NULL) {

        return 0;
    }

    if (tokens == NULL && token_count > 0) {
        return 0;
    }

    FILE *file = fopen(output_filename, "w");

    if (file == NULL) {

        fprintf(
            stderr,
            "Error: no se pudo crear %s\n",
            output_filename
        );

        return 0;
    }

    BeamerStats stats;

    calculate_stats(
        tokens,
        token_count,
        &stats
    );

    write_preamble(file);

    fprintf(file, "\\begin{document}\n\n");

    write_title_slide(file);

    write_process_slide(file);

    write_input_source_slide(
        file,
        source_filename
    );

    write_preprocessing_slide(file);

    write_temporary_file_slide(
        file,
        source_filename,
        preprocessed_filename
    );

    write_scanning_slide(file);

    write_token_collection_slide(file);

    write_beamer_generation_slide(file);

    write_pdf_generation_slide(file);

    write_results_slide(file);

    write_category_legend_slide(file);
    
    if (!write_source_slides(
            file,
            preprocessed_filename,
            tokens,
            token_count)) {

        fclose(file);

        return 0;
    }

    write_statistics_slide(
        file,
        &stats
    );

    write_histogram(
        file,
        &stats
    );

    write_pie_chart(
        file,
        &stats
    );

    write_error_slide(
        file,
        tokens,
        token_count
    );

    write_end_slide(file);

    fprintf(file, "\\end{document}\n");

    fclose(file);

    return 1;
}